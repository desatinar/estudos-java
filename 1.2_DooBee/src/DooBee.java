public class DooBee {
    public static void main(String[] args) throws Exception {
        int x = 1;
        while (x < 10) {
            System.out.print("Doo");
            System.out.print("Bee\n");
            x++;
        }
        if (x == 10) {
            System.out.println("Do");
        }
    }
}
